import { NextResponse } from "next/server";
import { auth } from "@clerk/nextjs/server";
import { db, users } from "@/lib/db";
import { eq, sql } from "drizzle-orm";

export async function POST() {
  const { userId: clerkId } = await auth();
  if (!clerkId) return NextResponse.json({ error: "unauthenticated" }, { status: 401 });

  const [admin] = await db.select({ role: users.role }).from(users).where(eq(users.clerkId, clerkId)).limit(1);
  if (admin?.role !== "admin") return NextResponse.json({ error: "forbidden" }, { status: 403 });

  await db.execute(sql`ALTER TABLE users ADD COLUMN IF NOT EXISTS bio text`);
  await db.execute(sql`ALTER TABLE users ADD COLUMN IF NOT EXISTS location text`);

  return NextResponse.json({ ok: true, message: "bio and location columns added" });
}
